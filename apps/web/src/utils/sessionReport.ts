import type { DemoSession } from "./sessionStorage";

function formatDuration(totalSeconds: number): string {
  const minutes = Math.floor(totalSeconds / 60);
  const seconds = totalSeconds % 60;

  return `${minutes} min ${seconds} sec`;
}

function createReportContent(session: DemoSession): string {
  return [
    "PULSECARE",
    "Portable Smart ECG Monitoring System",
    "SESSION REPORT",
    "",
    "========================================",
    "SESSION INFORMATION",
    "========================================",
    `Session ID: ${session.id}`,
    `Session Date: ${session.date}`,
    `Duration: ${formatDuration(session.durationSeconds)}`,
    "",
    "========================================",
    "RECORDED VALUES",
    "========================================",
    `Heart Rate: ${session.heartRate} BPM`,
    `Data Type: ${session.dataType}`,
    "",
    "========================================",
    "IMPORTANT SAFETY NOTICE",
    "========================================",
    "This report contains simulated demonstration data.",
    "The heart-rate value and ECG waveform have not been",
    "verified as measurements from a physical ECG device.",
    "",
    "This report is intended for educational and project",
    "demonstration purposes only. It is not a medical",
    "report and must not be used for diagnosis, treatment,",
    "or medical decision-making.",
    "",
    "Device connection and real sensor readings must be",
    "verified separately before reporting actual data.",
    "",
    "Generated by PulseCare",
  ].join("\n");
}

function createSafeFilename(sessionId: string): string {
  const safeId = sessionId.replace(/[^a-zA-Z0-9_-]/g, "_");

  return `PulseCare-Session-${safeId}.txt`;
}

export function exportSessionReport(session: DemoSession): void {
  const content = createReportContent(session);

  const blob = new Blob([content], {
    type: "text/plain;charset=utf-8",
  });

  const downloadUrl = URL.createObjectURL(blob);
  const link = document.createElement("a");

  link.href = downloadUrl;
  link.download = createSafeFilename(session.id);

  document.body.appendChild(link);
  link.click();
  link.remove();

  window.setTimeout(() => {
    URL.revokeObjectURL(downloadUrl);
  }, 1000);
}

